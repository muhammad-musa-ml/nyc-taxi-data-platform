"""Render the dbt lineage graph as a Mermaid diagram plus a model table, from dbt's own manifest.

    cd dbt && dbt parse --profiles-dir . && cd ..
    python scripts/lineage.py                       # reads dbt/target/manifest.json, writes docs/lineage.md

Nothing here is typed by hand: every node, edge, materialization and test count comes from ``manifest.json``.
"""
from __future__ import annotations

import argparse
import json
import re
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LAYERS = [("source", "Sources"), ("seed", "Seeds"), ("staging", "Staging"),
          ("intermediate", "Intermediate"), ("marts", "Marts")]


def layer_of(node: dict) -> str:
    kind = node["resource_type"]
    if kind in ("source", "seed"):
        return kind
    parts = Path(node["original_file_path"]).parts
    return parts[1] if len(parts) > 2 and parts[0] == "models" else "marts"


def ident(unique_id: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", unique_id)


def label(node: dict) -> str:
    if node["resource_type"] == "source":
        return f"{node['source_name']}.{node['name']}"
    return node["name"]


def collect(manifest: dict) -> tuple[dict[str, dict], list[tuple[str, str]], Counter]:
    nodes: dict[str, dict] = {}
    for uid, node in {**manifest["sources"], **manifest["nodes"]}.items():
        if node["resource_type"] in ("model", "seed", "source"):
            nodes[uid] = node
    edges = sorted({(parent, uid) for uid, node in nodes.items() if node["resource_type"] != "source"
                    for parent in node.get("depends_on", {}).get("nodes", []) if parent in nodes})
    tests: Counter = Counter()
    for node in manifest["nodes"].values():  # generic tests name the one model they belong to
        if node["resource_type"] == "test" and node.get("attached_node") in nodes:
            tests[node["attached_node"]] += 1
    return nodes, edges, tests


def mermaid(nodes: dict[str, dict], edges: list[tuple[str, str]]) -> str:
    lines = ["```mermaid", "flowchart LR"]
    for key, title in LAYERS:
        members = sorted((uid for uid, n in nodes.items() if layer_of(n) == key), key=lambda u: label(nodes[u]))
        if not members:
            continue
        lines.append(f'  subgraph {key}["{title}"]')
        lines += [f'    {ident(uid)}["{label(nodes[uid])}"]' for uid in members]
        lines.append("  end")
    lines += [f"  {ident(a)} --> {ident(b)}" for a, b in edges]
    lines.append("```")
    return "\n".join(lines)


def first_sentence(text: str) -> str:
    text = " ".join((text or "").split())
    match = re.match(r"(.+?[.!?])(\s|$)", text)
    return (match.group(1) if match else text).replace("|", "/")


def table(nodes: dict[str, dict], tests: Counter) -> str:
    rows = ["| model | layer | materialization | tests | what it is |", "|---|---|---|---:|---|"]
    for key, _ in LAYERS:
        for uid in sorted((u for u, n in nodes.items() if layer_of(n) == key), key=lambda u: label(nodes[u])):
            node = nodes[uid]
            kind = node["resource_type"]
            how = {"source": "source", "seed": "seed"}.get(kind) or node["config"].get("materialized", "view")
            rows.append(f"| `{label(node)}` | {key} | {how} | {tests.get(uid, 0)} | {first_sentence(node.get('description', ''))} |")
    return "\n".join(rows)


def render(manifest: dict) -> str:
    nodes, edges, tests = collect(manifest)
    meta = manifest.get("metadata", {})
    stamp = f"dbt {meta.get('dbt_version', '?')}, generated {meta.get('generated_at', '?')}"
    singular = sum(1 for n in manifest["nodes"].values()
                   if n["resource_type"] == "test" and not n.get("attached_node"))
    return "\n".join([
        "# Lineage",
        "",
        "Generated by `scripts/lineage.py` from dbt's `manifest.json` (" + stamp + "). Edit the dbt project, not this file.",
        "",
        mermaid(nodes, edges),
        "",
        table(nodes, tests),
        "",
        f"Generic tests attached to these models: {sum(tests.values())}. Singular tests in `dbt/tests/`, "
        f"each spanning several models (row-count and total reconciliation against the raw layer, the row "
        f"rules, the quarantine reasons): {singular}.",
        "",
    ])


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--manifest", default=str(ROOT / "dbt" / "target" / "manifest.json"))
    parser.add_argument("--out", default=str(ROOT / "docs" / "lineage.md"))
    args = parser.parse_args()
    manifest = json.loads(Path(args.manifest).read_text(encoding="utf-8"))
    Path(args.out).write_text(render(manifest), encoding="utf-8", newline="\n")
    nodes, edges, tests = collect(manifest)
    print(f"wrote {args.out}: {len(nodes)} nodes, {len(edges)} edges, {sum(tests.values())} attached tests")


if __name__ == "__main__":
    main()
